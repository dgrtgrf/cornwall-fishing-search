#!/usr/bin/env python3
"""Workstream 1 (numeric part): UKHO EasyTide predictions for every Cornish / Scilly port.
Fetches fresh JSON (saved with the fetch time), then writes fishing/research/tides.md tables.
Usage: build_tides.py <repo_root>"""
import sys, json, time, datetime as dt, pathlib, urllib.request
ROOT = pathlib.Path(sys.argv[1]); RAW = ROOT/'fishing/research/raw/tides'; RAW.mkdir(parents=True, exist_ok=True)
STATIONS = [  # id, name, sector(s) it is the reference for
 ('0543','Bude'),('0544','Boscastle'),('0544A','Port Isaac'),('0545','Padstow'),('0545A','Wadebridge'),('0546','Newquay'),
 ('0546A','Perranporth'),('0547','St Ives'),('0547A','Cape Cornwall'),('0548','Sennen Cove'),('0001',"St Mary's (Scilly)"),
 ('0002','Newlyn (Penzance)'),('0002A','Porthleven'),('0003','Lizard Point'),('0004','Coverack'),('0004A','Helford River entrance'),
 ('0005','Falmouth'),('0005A','Truro'),('0007','Mevagissey'),('0007A','Par'),('0008','Fowey'),('0008A','Lostwithiel'),('0011','Looe'),
 ('0012','Whitsand Bay'),('0014','Plymouth (Devonport)'),('0014E','Jupiter Point (Lynher)'),('0014F','St Germans'),('0014A','Saltash'),
 ('0014B','Cargreen'),('0014C','Cotehele Quay'),('0089','Dover (stream reference)'),('0496','Milford Haven (stream reference)')]
stamp = dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%MZ')
data = {}
import glob as _g
REUSE = len(sys.argv) > 2 and sys.argv[2] == 'reuse'
for sid, name in STATIONS:
    if REUSE:
        prev = sorted(_g.glob(str(RAW/f'easytide_{sid}_*.json')))
        if prev:
            data[sid] = json.load(open(prev[-1])); stamp = prev[-1].split('_')[-1].replace('.json',''); continue
    url = f'https://easytide.admiralty.co.uk/Home/GetPredictionData?stationId={sid}'
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (research script)'})
            raw = urllib.request.urlopen(req, timeout=40).read()
            d = json.loads(raw); break
        except Exception as e:
            d = None; time.sleep(2)
    if d is None: print('FAILED', sid, name); continue
    (RAW/f'easytide_{sid}_{stamp}.json').write_bytes(raw)
    data[sid] = d
P = lambda s: dt.datetime.fromisoformat(s.replace('Z',''))
def events(sid, day):
    return [(P(e['dateTime']), 'HW' if e['eventType']==0 else 'LW', e['height']) for e in data[sid]['tidalEventList'] if e['dateTime'][:10]==day and e['height'] is not None]
def allev(sid):
    return [(P(e['dateTime']), 'HW' if e['eventType']==0 else 'LW', e['height'], e.get('isApproximateTime'), e.get('isApproximateHeight')) for e in data[sid]['tidalEventList']]
def series(sid):
    return [(P(h['dateTime']), h['height']) for h in data[sid].get('tidalHeightOccurrenceList') or []]
def interp(ser, t):
    for (t0,h0),(t1,h1) in zip(ser, ser[1:]):
        if t0 <= t <= t1:
            f = (t-t0).total_seconds()/max(1,(t1-t0).total_seconds()); return h0 + f*(h1-h0)
    return None
out = []
W = out.append
W('# Workstream 1 - Tides for Sunday 22 November 2026 (numeric part)\n')
W(f'**Source (grade A):** UK Hydrographic Office, Admiralty EasyTide prediction API `https://easytide.admiralty.co.uk/Home/GetPredictionData?stationId=<id>`; fetched {stamp} (UTC); raw JSON saved in `fishing/research/raw/tides/easytide_<id>_{stamp}.json`. All times are **GMT (= UTC = UK clock time in November)**; heights are metres above **Chart Datum** of each port. Predictions are astronomical only (no surge / pressure effect - see section 6). Generated by `fishing/tools/tides/build_tides.py`.\n')
lp = data['0002'].get('lunarPhaseList') or []
W(f"EasyTide lunar phase list for the 7-day window: {json.dumps(lp)} (lunarPhaseType 3 = full moon).\n")
W('Tidal streams, estuary lags and pilotage-type detail are in `tidal_streams.md` (separate stream).\n')
W('## 1. High and low waters, 21-23 November 2026\n')
W('| Port (EasyTide id) | 21 Nov | 22 Nov | 23 Nov |\n|---|---|---|---|')
for sid, name in STATIONS:
    if sid not in data: W(f'| {name} ({sid}) | NOT FOUND (API fetch failed) | | |'); continue
    cells = []
    for day in ('2026-11-21','2026-11-22','2026-11-23'):
        cells.append('; '.join(f"{k} {t:%H:%M} {h:.2f} m" for t,k,h in events(sid, day)) or 'no events returned')
    W(f'| {name} ({sid}) | ' + ' | '.join(cells) + ' |')
W('\nNote: for some secondary ports the API returns HW/LW with `height = null` or approximate flags (e.g. drying upper-estuary ports where LW falls below the gauge); those events are omitted above and listed in section 5.\n')
W('## 2. Size of the tide on 22 November: range and position in the spring-neap cycle\n')
W('Ranges are computed from consecutive HW/LW pairs. "% of window max" compares the largest range on 22 Nov with the largest range in the 7-day EasyTide window (which runs past the full moon of 24 Nov 14:53 GMT, so contains the following spring peak or most of the rise to it).\n')
W('| Port | Ranges on 22 Nov (m) | Largest range 20 Nov | Largest range in 7-day window (date) | 22 Nov as % of window max |\n|---|---|---|---|---|')
rng = {}
for sid, name in STATIONS:
    if sid not in data: continue
    ev = [e for e in allev(sid) if e[2] is not None]
    pairs = [(a[0], abs(a[2]-b[2])) for a,b in zip(ev, ev[1:]) if a[1]!=b[1]]
    if not pairs: continue
    d22 = [r for t,r in pairs if t.strftime('%Y-%m-%d')=='2026-11-22']
    d20 = [r for t,r in pairs if t.strftime('%Y-%m-%d')=='2026-11-20']
    mx = max(pairs, key=lambda x:x[1])
    if d22:
        rng[sid] = (max(d22), mx[1])
        W(f"| {name} | {', '.join(f'{r:.2f}' for r in d22)} | {max(d20):.2f} | {mx[1]:.2f} ({mx[0]:%d %b}) | {100*max(d22)/mx[1]:.0f}% |" if d20 else f"| {name} | {', '.join(f'{r:.2f}' for r in d22)} | n/a | {mx[1]:.2f} ({mx[0]:%d %b}) | {100*max(d22)/mx[1]:.0f}% |")
W('\n## 3. Hour-by-hour predicted height on 22 November (m above Chart Datum)\n')
W('Interpolated linearly from the half-hourly `tidalHeightOccurrenceList` series returned by the API (ports without a continuous series are omitted - Bude, Truro, Lostwithiel, Sennen Cove).\n')
hours = [dt.datetime(2026,11,22,h) for h in range(24)] + [dt.datetime(2026,11,23,0)]
W('| Port | ' + ' | '.join(f'{h:%H}' if h.day==22 else '24' for h in hours) + ' |\n|---|' + '---|'*len(hours))
for sid, name in STATIONS:
    if sid not in data: continue
    ser = series(sid)
    if not ser: continue
    vals = [interp(ser, h) for h in hours]
    W(f'| {name} | ' + ' | '.join('' if v is None else f'{v:.1f}' for v in vals) + ' |')
W('\n## 4. Tide state by hour on 22 November for each reference port\n')
W('State = hours after the previous turning point (e.g. `LW+2` = two hours into the flood, `HW+3` = three hours into the ebb); rate = change in height over the following hour (m/h, + flooding / - ebbing).\n')
W('| Port | ' + ' | '.join(f'{h:%H}' for h in hours[:-1]) + ' |\n|---|' + '---|'*24)
for sid, name in STATIONS:
    if sid not in data: continue
    ev = [e for e in allev(sid)]
    ser = series(sid)
    cells = []
    for h in hours[:-1]:
        prev = [e for e in ev if e[0] <= h]
        if not prev: cells.append('?'); continue
        p = prev[-1]; dh = (h-p[0]).total_seconds()/3600
        rate = ''
        if ser:
            a, b = interp(ser, h), interp(ser, h+dt.timedelta(hours=1))
            if a is not None and b is not None: rate = f' ({b-a:+.1f})'
        cells.append(f'{p[1]}+{dh:.1f}{rate}')
    W(f'| {name} | ' + ' | '.join(cells) + ' |')
W('\n## 5. Events flagged approximate or without heights by the API\n')
n = 0
for sid, name in STATIONS:
    if sid not in data: continue
    for t,k,h,at,ah in allev(sid):
        if t.strftime('%Y-%m-%d') in ('2026-11-21','2026-11-22','2026-11-23') and (h is None or at or ah):
            W(f'- {name}: {k} {t:%d %b %H:%M} height={h} approxTime={at} approxHeight={ah}'); n += 1
if n == 0: W('- none')
add = ROOT/'fishing/tools/tides/tides_addendum.md'
(ROOT/'fishing/research/tides.md').write_text('\n'.join(out)+'\n' + (add.read_text() if add.exists() else ''))
json.dump({sid: {'name': dict(STATIONS)[sid], 'events': [(t.isoformat(), k, h) for t,k,h,_,_ in allev(sid)], 'series': [(t.isoformat(), h) for t,h in series(sid)]} for sid in data}, open(RAW/f'easytide_all_{stamp}.json','w'))
print('stations ok', len(data), 'of', len(STATIONS), 'stamp', stamp)
for sid in ('0002','0545','0005','0014','0001','0543','0089'):
    if sid in data: print(dict(STATIONS)[sid], [f"{k} {t:%H:%M} {h:.2f}" for t,k,h in events(sid,'2026-11-22')], 'range22/max', rng.get(sid))
